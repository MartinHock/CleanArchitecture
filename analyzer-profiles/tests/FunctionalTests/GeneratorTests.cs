        // Assert
        firstResult.Code.ShouldBe(SuccessExitCode, firstResult.Error);
        secondResult.Code.ShouldBe(SuccessExitCode, secondResult.Error);
        File.GetLastWriteTimeUtc(output).ShouldBe(originalTimestamp);
    }

