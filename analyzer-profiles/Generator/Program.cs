using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

if (args.Length == 0 || args[0] is not ("generate" or "verify"))
{
    Console.Error.WriteLine("Usage: generate <matrix.json> <profile> <output.globalconfig> | verify <matrix.json>");
    return 2;
}
try
{
    var matrixPath = Path.GetFullPath(args[1]);
    using var document = JsonDocument.Parse(File.ReadAllText(matrixPath));
    var root = document.RootElement;
    if (args[0] == "verify")
    {
        foreach (var profile in new[] { "Default", "Strict", "Regulated", "AllEnabled" })
            Require(Resolve(root, profile).Count == 6, $"Missing rules for {profile}");
        var modified = JsonNode.Parse(File.ReadAllText(matrixPath))!;
        modified["categoryOverrides"]!["Design"] = "error";
        modified["ruleOverrides"]!["CA1062"] = "none";
        using var overridden = JsonDocument.Parse(modified.ToJsonString());
        Require(Resolve(overridden.RootElement, "Default")["CA1062"] == "none", "Rule override precedence failed");
        Console.WriteLine("PASS: four profiles and rule > category > profile precedence");
        return 0;
    }
    Require(args.Length == 4, "Expected matrix, profile and output path");
    var rules = Resolve(root, args[2]);
    var output = new StringBuilder("# Generated by AnalyzerProfileGenerator; do not edit\n is_global = true\n global_level = 100\n".Replace("\n ", "\n"));
    foreach (var rule in rules.OrderBy(x => x.Key, StringComparer.Ordinal))
        output.Append("dotnet_diagnostic.").Append(rule.Key).Append(".severity = ").Append(rule.Value).Append('\n');
    var path = Path.GetFullPath(args[3]);
    Directory.CreateDirectory(Path.GetDirectoryName(path)!);
    File.WriteAllText(path, output.ToString(), new UTF8Encoding(false));
    Console.WriteLine($"Generated {path} for {args[2]}");
    return 0;
}
catch (Exception ex) when (ex is ArgumentException or IOException or JsonException or IndexOutOfRangeException or InvalidOperationException)
{
    Console.Error.WriteLine(ex.Message);
    return 1;
}

static SortedDictionary<string, string> Resolve(JsonElement root, string profile)
{
    var profiles = root.GetProperty("profiles");
    Require(profiles.TryGetProperty(profile, out var selected), $"Unknown profile: {profile}");
    var categories = root.GetProperty("categoryOverrides");
    var overrides = root.GetProperty("ruleOverrides");
    var result = new SortedDictionary<string, string>(StringComparer.Ordinal);
    foreach (var rule in root.GetProperty("rules").EnumerateObject())
    {
        var category = rule.Value.GetString()!;
        Require(selected.TryGetProperty(category, out var severity), $"Unknown category: {category}");
        if (categories.TryGetProperty(category, out var categoryOverride)) severity = categoryOverride;
        if (overrides.TryGetProperty(rule.Name, out var ruleOverride)) severity = ruleOverride;
        var value = severity.GetString()!;
        Require(value is "none" or "silent" or "suggestion" or "warning" or "error", $"Invalid severity for {rule.Name}: {value}");
        result.Add(rule.Name, value);
    }
    return result;
}
static void Require(bool condition, string message)
{
    if (!condition) throw new ArgumentException(message);
}

